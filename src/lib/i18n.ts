const idx: Record<Lang, number> = { 'pt-BR': 0, en: 1, es: 2 };

export function translate(lang: Lang, key: string, params?: Record<string, string | number>): string {
  const row = D[key] || D[key.replace(/\.(m|u)$/, '')];
  let s = row ? row[idx[lang]] : key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function hasKey(key: string) { return key in D; }

export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem('tidyo.lang');
    if (saved === 'pt-BR' || saved === 'en' || saved === 'es') return saved;
  } catch { /* storage unavailable */ }
  const n = (navigator.language || 'en').toLowerCase();
  if (n.startsWith('pt')) return 'pt-BR';
  if (n.startsWith('es')) return 'es';
  return 'en';
}

