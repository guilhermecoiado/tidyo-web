-- Tidyo · ticket numbers (TDY-1043), topic and a screenshot attached to a support message
alter table public.support_tickets add column if not exists number bigint generated by default as identity (start with 1001);
alter table public.support_tickets add column if not exists topic text check (topic in ('billing', 'technical', 'idea', 'other'));
alter table public.support_messages add column if not exists attachment_path text;

insert into storage.buckets (id, name, public) values ('support-files', 'support-files', false) on conflict (id) do nothing;

-- Path: {user_id}/{file}. The person who sent it and the Tidyo team read it.
create policy "support files upload own"
  on storage.objects for insert to authenticated
  with check (bucket_id = 'support-files' and (storage.foldername(name))[1] = auth.uid()::text);
create policy "support files read"
  on storage.objects for select to authenticated
  using (bucket_id = 'support-files' and ((storage.foldername(name))[1] = auth.uid()::text or public.is_platform_admin()));
